export const TransactionResponseSchema = z.object({
  id: ZodSchemas.nanoid().openapi({ example: 'gnQjJatJSrhxaGtXeTuDd' }),
  merchantId: ZodSchemas.nanoid().openapi({ example: 'CRutyJmJHin46NXnRdCjN' }),
  preTransactionId: ZodSchemas.nanoid().nullable().optional().openapi({ example: 'eDNSaEjdyKFUYZBLGjqXH' }),
  provider: z.string().nullable().optional(),
  providerId: z.string().nullable().optional().openapi({ example: 'b8d32335507746d381daf2d38db89111c496089b15' }),
  status: z.enum(TransactionStatus).openapi({ example: TransactionStatus.PAID }),
  statusMessage: z.string().openapi({ example: 'changed status' }),
  statusHistory: z.array(TransactionStatusHistoryResponseSchema).openapi({ description: 'history of status changes' }),
  method: z.enum(PaymentMethod).openapi({ example: PaymentMethod.PIX }),
  methodSettings: TransactionMethodSettingsResponseSchema.openapi({ description: 'one of the schemas depending on the payment method' }),
  items: z.array(TransactionItemResponseSchema).openapi({ description: 'describe the items that compose the transaction' }),
  refunds: z.array(TransactionRefundResponseSchema).openapi({ description: 'list of refunds processed for this transaction' }),
  chargebacks: z.array(TransactionChargebackResponseSchema),
  shipping: TransactionShippingResponseSchema.optional().nullable().openapi({ description: 'shipping information' }),
  methodData: TransactionMethodDataResponseSchema.openapi({ description: 'one of the schemas depending on the payment method' }),
  paidData: TransactionPaidDataResponseSchema,
  amount: z.number().positive().int().openapi({
    description: 'total amount in cents for the transaction, including shipping and items',
    example: 5000,
  }),
  amountRefunded: z.number().nonnegative().int().openapi({ description: 'amount in cents that was refunded from the transaction', example: 0 }),
  amountChargedback: z.number().nonnegative().int(),
  customer: TransactionCustomerResponseSchema.optional().nullable().openapi({ description: 'customer information' }),
  notifyUrl: z.url().nullable().openapi({
    description: 'url that we will notify any transaction updates (via webhooks)',
    example: 'https://example.com/webhook',
  }),
  splits: z.array(TransactionSplitResponseSchema).openapi({
    description:
      'specify how the transaction will be splitted between one or more merchants. if null, current merchant will receive the total amount by default',
  }),
  externalId: z.string().nullable().openapi({ description: 'external id for the transaction', example: 'my_ext_id' }),
  externalSaleChannel: z.string().nullable().openapi({ description: 'channel where the transaction was made', example: 'ecommerce' }),
  antifraudData: TransactionAntifraudDataResponseSchema.optional().nullable(),
  metadata: z.record(z.string(), z.string()).openapi({ description: 'open field to store information', example: { key: 'value' } }),
  paidAt: z.date().nullable().openapi({ example: '2021-10-25T20:00:00.000Z' }),
  refundedAt: z.date().nullable().openapi({ example: '2021-10-25T20:00:00.000Z' }),
  chargedbackAt: z.date().nullable(),
  createdAt: z.date().openapi({ example: '2021-10-25T20:00:00.000Z' }),
  updatedAt: z.date().openapi({ example: '2021-10-25T20:00:00.000Z' }),
});

